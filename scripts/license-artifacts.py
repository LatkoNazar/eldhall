"""Generate/check fixed legal artifacts without installs, network or environment reads."""

from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
import sys
import tomllib
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
FONT_SPEC = importlib.util.spec_from_file_location("eldhall_font_source_policy", ROOT / "scripts/source-archive.py")
FONT_POLICY = importlib.util.module_from_spec(FONT_SPEC)
FONT_SPEC.loader.exec_module(FONT_POLICY)
APACHE_SHA256 = "43070e2d4e532684de521b885f385d0841030efa2b1a20bafb76133a5e1379c1"
CONTEXTS = {
    "api": "apps/api/licenses",
    "frontend": "apps/frontend/public/licenses",
    "landing": "apps/landing/public/licenses",
    "mcp-openapi": "apps/mcp-openapi/licenses",
}
BROWSER_PACKAGES = {
    "frontend": ("react", "react-dom", "scheduler", "vite", "@hugeicons/react", "@hugeicons/core-free-icons", "i18next", "react-i18next", "@babel/runtime", "html-parse-stringify", "use-sync-external-store"),
    "landing": ("vite", "i18next"),
}
BROWSER_LICENSE_FILES = {"vite": "LICENSE.md", "@hugeicons/react": "LICENSE.md", "@hugeicons/core-free-icons": "LICENSE.md"}


def read_binary(root: Path, relative: str, maximum: int = 1_048_576) -> bytes:
    path = root / relative
    if path.is_symlink() or not path.is_file() or path.stat().st_size > maximum:
        raise ValueError(f"Missing, linked or oversized licence input: {relative}")
    return path.read_bytes()


def read(root: Path, relative: str, maximum: int = 1_048_576) -> bytes:
    return read_binary(root, relative, maximum).replace(b"\r\n", b"\n")


def sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def encoded(value: dict) -> bytes:
    return (json.dumps(value, indent=2, ensure_ascii=False) + "\n").encode()


def browser_notices(root: Path, app: str, lock: dict) -> tuple[bytes, list[dict]]:
    parts = ["Browser component notices\n\nUpstream terms below are retained verbatim. Vite is listed for generated browser-runtime helpers; its build tool is not shipped in full.\n"]
    components = []
    for name in BROWSER_PACKAGES[app]:
        relative = f"apps/{app}/node_modules/{name}"
        metadata = json.loads(read(root, f"{relative}/package.json"))
        locked = lock["packages"][f"node_modules/{name}"]
        if metadata.get("version") != locked.get("version") or metadata.get("license") != "MIT" or locked.get("license") != "MIT":
            raise ValueError(f"Review browser component version/licence before regeneration: {app}/{name}")
        filename = BROWSER_LICENSE_FILES.get(name, "LICENSE")
        text = read(root, f"{relative}/{filename}", 262_144).decode("utf-8")
        # Vite's file contains its complete dependency notice inventory. Retain
        # that whole file rather than dropping upstream notices heuristically.
        if "Copyright" not in text or "Permission is hereby granted" not in text:
            raise ValueError(f"Browser copyright/licence text is missing: {app}/{name}")
        components.append({"name": name, "version": metadata["version"], "license": "MIT", "noticeSha256": sha(text.encode())})
        parts.append(f"\n{'=' * 72}\n{name} {metadata['version']}\n{'=' * 72}\n\n{text.rstrip()}\n")
    if app == "frontend":
        font_files = {name: read_binary(root, name) for name in FONT_POLICY.FONT_FILES}
        font = FONT_POLICY.verify_fonts(font_files)
        text = font_files[FONT_POLICY.FONT_ROOT + "OFL.txt"].decode("utf-8")
        components.append({"name": font["family"], "version": font["version"], "license": font["license"], "noticeSha256": sha(text.encode())})
        copyright_text = "\n".join(sorted({row["copyright"] for row in font["files"] if row["role"] == "font" and isinstance(row.get("copyright"), str)}))
        parts.append(f"\n{'=' * 72}\nGoogle Sans {font['version']} (font software; OFL-1.1)\n{'=' * 72}\n\n{copyright_text}\n\n{text}")
    return "".join(parts).encode(), components


JS_CHECKER = '''// Generated by scripts/license-artifacts.py; do not edit independently.
import { createHash } from 'node:crypto';
import { lstatSync, readFileSync } from 'node:fs';
const app = new URL('../', import.meta.url);
const directory = new URL(process.argv.includes('--dist') ? 'dist/licenses/' : '__LEGAL_DIRECTORY__', app);
const digest = data => createHash('sha256').update(data).digest('hex');
const readBytes = url => {
  const stat = lstatSync(url);
  if (!stat.isFile() || stat.isSymbolicLink() || stat.size > 1048576) throw new Error('Invalid legal artifact');
  return readFileSync(url);
};
const read = url => readBytes(url).toString('utf8').replace(/\\r\\n/g, '\\n');
const fontPaths = __FONT_PATHS__;
const publicDirectory = new URL(process.argv.includes('--dist') ? 'dist/' : 'public/', app);
try {
  const manifest = JSON.parse(read(new URL('manifest.json', directory)));
  const allowed = new Set(['LICENSE', 'NOTICE', 'LICENSING.md', 'THIRD_PARTY_NOTICES.md', 'BROWSER_NOTICES.txt']);
  if (manifest.format !== 'eldhall-legal-artifacts-v1' || manifest.projectLicense !== 'Apache-2.0') throw new Error('Invalid legal manifest');
  for (const [name, expected] of Object.entries(manifest.files)) {
    if (!allowed.has(name) || digest(read(new URL(name, directory))) !== expected) throw new Error('Legal file drift');
  }
  for (const name of ['LICENSE', 'NOTICE', 'LICENSING.md', 'THIRD_PARTY_NOTICES.md']) {
    if (!manifest.files[name]) throw new Error('Required legal file missing');
  }
  for (const [name, expected] of Object.entries(manifest.localInputs)) {
    if (!['package.json', 'package-lock.json'].includes(name) || digest(read(new URL(name, app))) !== expected) throw new Error('Package metadata drift');
  }
  const fonts = manifest.fontAssets ?? {};
  if (Object.keys(fonts).length !== fontPaths.length || fontPaths.some(name => !Object.hasOwn(fonts, name))) throw new Error('Font inventory drift');
  for (const name of fontPaths) {
    if (digest(readBytes(new URL(name, publicDirectory))) !== fonts[name]) throw new Error('Font asset drift');
  }
  console.log('Legal artifacts verified');
} catch {
  console.error('Legal artifact validation failed; run python3 scripts/license-artifacts.py --write from the repository root and review the changes.');
  process.exitCode = 1;
}
'''

PY_CHECKER = '''# Generated by scripts/license-artifacts.py; do not edit independently.
import hashlib
import json
import sys
from pathlib import Path

app = Path(__file__).resolve().parents[1]
directory = app / 'licenses'

def read(path):
    if path.is_symlink() or not path.is_file() or path.stat().st_size > 1048576:
        raise ValueError()
    return path.read_bytes().replace(b'\\r\\n', b'\\n')

try:
    manifest = json.loads(read(directory / 'manifest.json'))
    allowed = {'LICENSE', 'NOTICE', 'LICENSING.md', 'THIRD_PARTY_NOTICES.md'}
    if manifest['format'] != 'eldhall-legal-artifacts-v1' or manifest['projectLicense'] != 'Apache-2.0' or set(manifest['files']) != allowed:
        raise ValueError()
    for name, expected in manifest['files'].items():
        if hashlib.sha256(read(directory / name)).hexdigest() != expected:
            raise ValueError()
    for name, expected in manifest['localInputs'].items():
        if name not in {'pyproject.toml', 'uv.lock'} or hashlib.sha256(read(app / name)).hexdigest() != expected:
            raise ValueError()
    print('Legal artifacts verified')
except (OSError, ValueError, KeyError, TypeError):
    print('Legal artifact validation failed; regenerate from the repository root and review changes.', file=sys.stderr)
    raise SystemExit(1)
'''


def expected_artifacts(root: Path) -> dict[str, bytes]:
    license_text = read(root, "LICENSE", 65_536)
    if sha(license_text) != APACHE_SHA256:
        raise ValueError("Root LICENSE differs from the canonical Apache-2.0 template")
    canonical = {"LICENSE": license_text, "NOTICE": read(root, "NOTICE"),
                 "LICENSING.md": read(root, "docs/LICENSING.md").replace(b"(../LICENSE)", b"(LICENSE)").replace(b"(../NOTICE)", b"(NOTICE)"),
                 "THIRD_PARTY_NOTICES.md": read(root, "docs/THIRD_PARTY_NOTICES.md")}
    if json.loads(read(root, "packages/analytics/package.json")).get("license") != "Apache-2.0":
        raise ValueError("Analytics project licence metadata is missing")
    if json.loads(read(root, "packages/i18n/package.json")).get("license") != "Apache-2.0":
        raise ValueError("Localization project licence metadata is missing")
    result = {}
    for app, directory in CONTEXTS.items():
        files = dict(canonical)
        inputs = {}
        components = []
        if app == "mcp-openapi":
            inputs = {name: read(root, f"apps/{app}/{name}") for name in ("pyproject.toml", "uv.lock")}
            project = tomllib.loads(inputs["pyproject.toml"].decode())["project"]
            if project.get("license") != "Apache-2.0" or project.get("license-files") != ["licenses/*"]:
                raise ValueError("Python project licence metadata/files are missing")
        else:
            inputs = {name: read(root, f"apps/{app}/{name}") for name in ("package.json", "package-lock.json")}
            package, lock = (json.loads(inputs[name]) for name in ("package.json", "package-lock.json"))
            if package.get("license") != "Apache-2.0" or lock["packages"][""].get("license") != "Apache-2.0":
                raise ValueError(f"Project licence metadata is missing: {app}")
            if app in BROWSER_PACKAGES:
                if lock["packages"]["../../packages/analytics"].get("license") != "Apache-2.0":
                    raise ValueError(f"Linked analytics licence metadata is missing: {app}")
                files["BROWSER_NOTICES.txt"], components = browser_notices(root, app, lock)
        manifest = {"format": "eldhall-legal-artifacts-v1", "artifact": app, "projectLicense": "Apache-2.0",
                    "scope": "Project contributions only; see LICENSING.md. Not a complete image SBOM or publication approval.",
                    "files": {name: sha(data) for name, data in files.items()},
                    "localInputs": {name: sha(data) for name, data in inputs.items()}, "browserComponents": components,
                    "fontAssets": {name.removeprefix("apps/frontend/public/"): sha(read_binary(root, name)) for name in sorted(FONT_POLICY.FONT_FILES)} if app == "frontend" else {}}
        result.update({f"{directory}/{name}": data for name, data in files.items()})
        result[f"{directory}/manifest.json"] = encoded(manifest)
        checker = PY_CHECKER if app == "mcp-openapi" else JS_CHECKER.replace("__LEGAL_DIRECTORY__", "public/licenses/" if app in BROWSER_PACKAGES else "licenses/").replace("__FONT_PATHS__", json.dumps([name.removeprefix("apps/frontend/public/") for name in sorted(FONT_POLICY.FONT_FILES)] if app == "frontend" else []))
        result[f"apps/{app}/scripts/check-licenses.{'py' if app == 'mcp-openapi' else 'mjs'}"] = checker.encode()
    return result


def check(root: Path) -> list[str]:
    errors = []
    for relative, expected in expected_artifacts(root).items():
        try:
            if read(root, relative) != expected:
                errors.append(relative)
        except (OSError, ValueError):
            errors.append(relative)
    return errors


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="regenerate fixed legal files for review")
    parser.add_argument("--check", action="store_true", help="fail if generated files drift (default)")
    args = parser.parse_args()
    try:
        if args.write and args.check:
            parser.error("choose --write or --check")
        if args.write:
            artifacts = expected_artifacts(ROOT)
            for relative, data in artifacts.items():
                target = ROOT / relative
                if target.is_symlink():
                    raise ValueError(f"Refusing linked generated target: {relative}")
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(data)
            print(f"Generated {len(artifacts)} legal artifacts; review before publication")
        else:
            errors = check(ROOT)
            if errors:
                print("Legal artifact drift:\n" + "\n".join(errors), file=sys.stderr)
                return 1
            print("Canonical and generated legal artifacts match")
    except (OSError, ValueError, KeyError, TypeError) as error:
        print(f"Legal artifact generation/check failed: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
